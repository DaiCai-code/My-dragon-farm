package com.itElton.Abstract.BenefitsOfAbstract;

public class Demo {
    public static void main(String[] args) {
       /*
            抽象类的主要目的是为子类提供一个通用的模板，并强制子类实现某些特定的方法。
        父类知道每个子类都要做某个行为，但每个子类要做的情况不一样，父类就定义成抽象方法，
        交给子类去重写实现，我们设计这样的抽象类，就是为了更好的支持多态。
            比如：动物都会叫唤，但每种动物的叫唤方式不同，所以不能在父类中实现具体的叫唤功能，
        而需要在各个不同的子类中才能实现。但无论哪种动物，都会叫唤，所以我们可以在父类Animal
        类中定义一个叫唤的方法，但是又不确定又该如何叫唤，所以可以将方法声明成抽象的。这样一来，
        所有继承该类的子类,都得提供这个方法，就实现了强制子类实现特定方法的目的。
        */
    }
}
