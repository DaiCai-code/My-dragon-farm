# 如果我们有两个字符串(文本)字面量，可以将其拼接成一个字符串，通过+号即可完成，如:
print("晚上好" + "大家辛苦了")
# 区别于以下的方式，是会出现空格
print("晚上好" , "大家辛苦了")

name = "daizhitong"
age = 18
money = 1000

# 注意：这里所说的拼接只能是字符串的拼接，数字拼接需要用str()来进行类型转换，否则会报错
print("我是"+ name + "年龄" + str(age) + "有" + str(money) + "元")

# 字符串还可以用*来进行连接，如下所示，效果就是输出20个你好
print("你好"*20)