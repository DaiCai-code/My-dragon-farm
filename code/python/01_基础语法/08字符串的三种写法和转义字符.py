# 字符串存在以下三种写法：单引号，双引号，三引号
print("这是字符串的第一种写法")
print('这是字符串的第二种写法')
print(""""这是字符串的第三种写法""")
# 而且它们还可以嵌套使用
print('"这是单引号套双引号的写法"')

#扩展转义字符()
#  \   转义(转换含义)
# 某些字符有特殊功能，如"2个成对表示字符中有特殊功能
#转义字符的作用:( \ 转义字符会影响它后面的字符)
#1，有特珠功能，被转义字符后，将没有特殊功能了
# 2.没有特殊功能，被转义字符后，有特殊功能了

# 这里前两个"相互匹配，后两个两个"相互匹配反而不把文心一言当字符串了，这里使用\分隔开,从而让第一个"匹配到最后一个"
# address1 = ""文心一言""这样写会报错
address1 = "\"文心一言\""
print(address1)

# 这里文心n一言本来中n没什么特殊功能，会直接打印出来，但是加了\之后\n便有了换行（newline）的特殊功能
address2 = "文心\n一言"
print(address2)

