# 1.掌握字面量的含义
#
# 代码中，被写在代码中的固定的值，称之为字面量
#
# 2.常见的字面量类型
#
# 我们目前了解:整数、浮点数、字符串这三类即可
#
# 3.如何基于print语句完成各类字面量的输出
#
# print(字面量)，如:
#
# print(10),输出整数10
#
# print(13.14)，输出浮点数13.14
#
# print("黑马程序员")，输出字符串:黑马程序员

# 字符串(string)，又称文本，是由任意数量的字符如中文、英文、各类符号、数字等组成。所以叫做字符的串

