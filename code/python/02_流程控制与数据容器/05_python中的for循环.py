# while循环的循环条件是自定义的，自行控制循环条件
# for循环是一种”轮询”机制，是对一批内容进行”逐个处理”

# for临时变量in待处理数据集:
#    循环满足条件时执行的代码

name = "itdaizhitong"
for x in name:
    print(x)
# 可以看出，for循环是将字符串的内容: 依次取出所以，for循环也被称之为: 遍历循环

# 关于变量作用域的规范
# 1.for循环中的临时变量，其作用域限定为:
#
# 循环内
#
# 2.这种限定:
#
# ·是编程规范的限定，而非强制限定
#
# ·不遵守也能正常运行，但是不建议这样做
#
# ·如需访问临时变量，可以预先在循环外定义它