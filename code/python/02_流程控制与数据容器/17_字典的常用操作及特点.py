# 语法:字典.pop(Key)，结果:获得指定Key的Value，同时字典被修改，指定Key的数据被删除

# 3.清空字典
# 语法:字典.clear()，结果:字典被修改，元素被清空

# 4.获取全部的key
# 语法:字典.keys()，结果:得到字典中的全部Key

