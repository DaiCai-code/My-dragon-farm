# 字典的特点
# 可以容纳多个数据
# 可以容纳不同类型的数据
# 每一份数据是KeyValue键值对
# 可以通过Key获取到Value，Key不可重复(重复会覆盖)
# 不支持下标索引
# 可以修改(增加或删除更新元素等)
# 支持for循环，不支持while循环