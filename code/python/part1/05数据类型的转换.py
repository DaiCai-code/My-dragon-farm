# 数据类型之间，在特定的场景下，是可以相互转换的，如字符串转数字、数字转字符串等
# 语句(函数)                   说明
#
# int(x)                  将x转换为一个整数
#
# float(x)                将x转换为一个浮点数
#
# str(x)                  将对象x转换为字符串
# 这三个语句都是带有返回值的
a = 666
b = "777"
c = "888.888"
b = int(b)
a = str(a)
c = float(c)
print(type(a))
print(type(b))
print(type(c))
print(a,b,c)
# 类型转换不是万能的，毕竟强扭的瓜不会甜，我们需要注意:
# 1.任何类型，都可以通过str()，转换成字符串
# 2.字符串内必须全部是数字才能转换为数字类型







