# 1.打开文件        这里注意把参数调成w模式
# w模式:如果文件不存在则新建
# 如果文件存在，则清空原有内容，写入新的
f = open ("D:/python.txt","w",encoding = "utf-8")

# 2.文件写入
f.write('66666666666666666666666')

# 3.内容刷新
f.flush()

# 注意:
# 当调用flush的时候，内容会真正写入文件0
# 直接调用write，内容并未真正写入文件，而是会积攒在程序的内存中，称之为缓冲区
# 这样做是避免频繁的操作硬盘，导致效率下降(攒一堆，一次性写磁盘)

f.close()

# 总结
# 1.写入文件使用open函数的”w”模式进行写入
#
# 2.写入的方法:
#
# wirte()，写入内容
#
# flush()，刷新内容到硬盘中
#
# 3.注意事项:
#
# w模式，文件不存在，会创建新文件
#
# w模式，文件存在，会清空原有内容
#
# close()方法，带有flush()方法的功能