#**********************************************************************************************************************

# - 全局变量：在函数、推导式之外定义的变量，称之为全局变量，在整个文件中（包括函数内）都可以使用（通常定义在文件的顶部）。
# - 局部变量：在函数、推导式内部定义的变量，称之为局部变量，只能在该函数内部使用，外部无法访问(执行完毕后，会自动销毁其内部局部变量)
# #全局变量
# variable1 = 100
#
# def method_a():
#     #局部变量
#     variable2 = 200
#     print(variable1, variable2)
#
# method_a()  #100 200

#**********************************************************************************************************************

#变量的优先级：在使用一个变量时，首先看当前作用域内有没有定义过该变量，如果有，就使用
#           如果在该作用域内，没有定义过该变量，去外层作用域寻找有没有定义过，如果定义过，直接使用
# num1 = 100
# num3 = 300
# def method_b():
#     num1 = 200
#     print(num1, num3)   # 200 300
#
# method_b()  #200 300
# print(num3) #300

#**********************************************************************************************************************

#global: 在函数内如果想要使用函数外的全局变量，需要使用该单词修饰
#使用方式：需要先使用global修饰变量，然后再使用

num1 = 100

def method_c():
    global num1
    num1 = 200
    print(num1) #200

method_c()  #200
#利用global关键字在函数内就把全局变量num1给改了
print(num1) #200
